namespace Latiprimere.EndToEnd;

/// <summary>
/// How a person answered a question about what they can see.
/// </summary>
public enum PersonReply
{
	/// <summary>
	/// Yes, it is so.
	/// </summary>
	Yes = 0,

	/// <summary>
	/// No, it isn't.
	/// </summary>
	No = 1,

	/// <summary>
	/// The person didn't answer, for example because they couldn't tell.
	/// </summary>
	Skipped = 2
}
